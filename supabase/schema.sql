create table if not exists public.value_entries (
  slug text primary key,
  kind text not null default 'unit',
  base_value numeric not null default 1,
  gems numeric not null default 1,
  coins numeric not null default 1,
  demand text not null default 'Normal',
  scarcity text not null default 'Standard',
  trend text not null default 'stable',
  notes text,
  updated_by uuid references auth.users(id) on delete set null,
  updated_at timestamptz not null default now()
);

create table if not exists public.value_change_log (
  id bigint generated by default as identity primary key,
  slug text not null,
  kind text not null default 'unit',
  old_value jsonb,
  new_value jsonb,
  changed_by uuid references auth.users(id) on delete set null,
  changed_at timestamptz not null default now()
);

alter table public.admin_users enable row level security;
alter table public.value_entries enable row level security;
alter table public.value_change_log enable row level security;

create or replace function public.is_value_editor()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.admin_users au
    where lower(au.email) = lower(coalesce(auth.jwt() ->> 'email', ''))
      and au.role in ('owner', 'admin', 'editor')
  );
$$;

-- Admin roles: logged-in users can read their own role. Owners can read every role.
drop policy if exists "read own admin role" on public.admin_users;
create policy "read own admin role"
on public.admin_users
for select
to authenticated
using (
  lower(email) = lower(coalesce(auth.jwt() ->> 'email', ''))
  or exists (
    select 1 from public.admin_users owner_row
    where lower(owner_row.email) = lower(coalesce(auth.jwt() ->> 'email', ''))
      and owner_row.role = 'owner'
  )
);

-- Public site can read values.
drop policy if exists "public read values" on public.value_entries;
create policy "public read values"
on public.value_entries
for select
to anon, authenticated
using (true);

-- Permissioned editors can insert/update/delete values.
drop policy if exists "editors insert values" on public.value_entries;
create policy "editors insert values"
on public.value_entries
for insert
to authenticated
with check (public.is_value_editor());

drop policy if exists "editors update values" on public.value_entries;
create policy "editors update values"
on public.value_entries
for update
to authenticated
using (public.is_value_editor())
with check (public.is_value_editor());

drop policy if exists "editors delete values" on public.value_entries;
create policy "editors delete values"
on public.value_entries
for delete
to authenticated
using (public.is_value_editor());

-- Public can read change logs. Editors can insert logs.
drop policy if exists "public read value logs" on public.value_change_log;
create policy "public read value logs"
on public.value_change_log
for select
to anon, authenticated
using (true);

drop policy if exists "editors insert value logs" on public.value_change_log;
create policy "editors insert value logs"
on public.value_change_log
for insert
to authenticated
with check (public.is_value_editor());

