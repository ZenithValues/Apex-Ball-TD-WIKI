#!/usr/bin/env node
/**
 * stamp-build.mjs — one honest identity for every front-end build.
 *
 * Why this exists (2026-11-12): the admin dashboard had a single
 * "Up to date (<worker version>) — all features live." line. It only ever
 * described the CLOUDFLARE WORKER, so it happily said "up to date" while the
 * deployed GitHub Pages bundle was months old. Nothing on the site told you
 * which front-end build you were actually looking at.
 *
 * This script runs before every build and writes:
 *   src/generated/buildStamp.js   — BUILD_STAMP + RELEASE_ID for the app
 *   public/build.json             — the same info, fetchable from the live site
 *   public/sw.js                  — cache name rotated to the new build id
 *
 * So after deploying, `curl <site>/build.json` answers "what is live?" with no
 * guessing, and the admin dashboard can show the running build next to the
 * worker version.
 */
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));

// ---- hash the source tree -------------------------------------------------
function walk(dir, out = []) {
  for (const entry of readdirSync(dir)) {
    if (entry === 'node_modules' || entry === 'dist' || entry.startsWith('.')) continue;
    const full = join(dir, entry);
    const stat = statSync(full);
    if (stat.isDirectory()) {
      if (entry === 'social') continue; // 85 MB of generated PNGs — not identity
      walk(full, out);
    } else if (/\.(jsx?|mjs|css|json|html|md|txt|svg|webmanifest)$/.test(entry)) {
      out.push(full);
    }
  }
  return out;
}

const files = [...walk(join(root, 'src')), join(root, 'package.json'), join(root, 'index.html')]
  .sort();
const hash = createHash('sha1');
for (const file of files) {
  hash.update(relative(root, file));
  hash.update(readFileSync(file));
}
const shortHash = hash.digest('hex').slice(0, 8);

const builtAt = new Date();
const date = builtAt.toISOString().slice(0, 10);
const id = `${date}-${shortHash}`;
const label = `Batch 4 · ${date} · ${shortHash}`;

// ---- src/generated/buildStamp.js -----------------------------------------
const generatedDir = join(root, 'src', 'generated');
mkdirSync(generatedDir, { recursive: true });
writeFileSync(join(generatedDir, 'buildStamp.js'), `// AUTO-GENERATED by scripts/stamp-build.mjs — do not hand-edit.
// Regenerate with: node scripts/stamp-build.mjs (runs before every build)
export const BUILD_STAMP = {
  id: ${JSON.stringify(id)},
  hash: ${JSON.stringify(shortHash)},
  date: ${JSON.stringify(date)},
  builtAt: ${JSON.stringify(builtAt.toISOString())},
  label: ${JSON.stringify(label)},
};

// Service-worker release id — changes with every build, which rotates the
// offline cache and forces installed clients onto the new assets.
export const RELEASE_ID = ${JSON.stringify(id)};
`);

// ---- public/build.json ----------------------------------------------------
writeFileSync(join(root, 'public', 'build.json'), `${JSON.stringify({
  id,
  hash: shortHash,
  date,
  builtAt: builtAt.toISOString(),
  label,
  routes: 'see dist/sitemap.xml',
}, null, 2)}\n`);

// ---- public/sw.js cache rotation -----------------------------------------
const swPath = join(root, 'public', 'sw.js');
let sw = readFileSync(swPath, 'utf8');
const cacheBefore = sw.match(/const CACHE_NAME = '([^']+)';/)?.[1] || null;
sw = sw.replace(/const CACHE_NAME = '[^']+';/, `const CACHE_NAME = 'apex-values-offline-${shortHash}';`);
writeFileSync(swPath, sw);

console.log(`[stamp] build ${id} (${files.length} source files hashed)` +
  (cacheBefore ? ` · offline cache ${cacheBefore} → apex-values-offline-${shortHash}` : ''));
